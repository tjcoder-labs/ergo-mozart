import json
import os

def compile_reaper_lua(json_path, output_lua_path):
    with open(json_path, 'r') as f:
        song = json.load(f)

    lua_code = []
    lua_code.append("-- Generated by Ergo-Mozart Compiler")
    lua_code.append(f"reaper.SetProjectTempTempo({song['song_metadata']['tempo']})")
    lua_code.append("")

    for track in song['tracks']:
        name = track['name']
        lua_code.append(f"-- Track: {name}")
        lua_code.append(f"reaper.InsertTrackAtIndex(0, true)")
        lua_code.append(f"local track = reaper.GetTrack(0, 0)")
        lua_code.append(f"reaper.GetSetMediaTrackInfo_String(track, 'P_NAME', {repr(name)}, true)")
        # Note: Plugin loading is complex in REAPER API as it depends on the exact plugin name in the system
        lua_code.append(f"-- TODO: Load plugin {track['plugin']} with preset {track['preset']}")
        lua_code.append("")

    with open(output_lua_path, 'w') as f:
        f.write("\n".join(lua_code))

if __name__ == "__main__":
    base_dir = "/home/tj/ergo/workspaces/personal-tj-tjcoder-com/ergo-mozart"
    compile_reaper_lua(
        os.path.join(base_dir, "song_state.json"),
        os.path.join(base_dir, "build_song.lua")
    )
    print("Successfully compiled song_state.json to build_song.lua")
